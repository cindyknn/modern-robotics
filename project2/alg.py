########## Task 1: Primitive Wrenches ##########

def primitive_wrenches(mesh, grasp, mu=0.2, n_edges=8):
    """
    Find the primitive wrenches for each contact of a grasp.
    args:   mesh: The object mesh model.
                  Type: trimesh.base.Trimesh
           grasp: The indices of the mesh triangles being contacted.
                  Type: list of int
              mu: The friction coefficient of the mesh surface.
                  (default: 0.2)
         n_edges: The number of edges of the friction polyhedral cone.
                  Type: int (default: 8)
    returns:   W: The primitive wrenches.
                  Type: numpy.ndarray of shape (len(grasp) * n_edges, 6)
    """
    ########## TODO ##########
    W = np.zeros(shape=(len(grasp) * n_edges, 6))

    # 1. compute the polyhedral friction cone for each contact, which is represented by n edges number of primitive forces. 
        # every primitive force should be scaled such that the magnitude of its normal force is ||f|| = sqrt(mu^2 + 1)
    # 2.  for each primitive force f, compute the corresponding torque τ generated by this force to obtain the primitive wrench. 
        # In the end, the returned value W of the function should be a numpy.ndarray, each row of which is one primitive wrench [f^T, t^T].
    # Eg: given a grasp grasp = [2, 7, 36, 94] consisting of four contacts, the returned W should be of shape (4 * n edges, 6). 
        # Every n edges rows of W are the primitive wrenches for one contact of the grasp.

    cm = mesh.center_mass
    con_pts = utils.get_centroid_of_triangles(mesh, grasp)
        
    for i, face_id in enumerate(grasp):
        n = mesh.face_normals[face_id]
        
        # Find 2 orthogonal vectors on tangent plane to build the cone
        vec = np.array([1.0, 0.0, 0.0])
        if np.abs(np.dot(n, vec)) > 0.99:
            vec = np.array([0.0, 1.0, 0.0])
        t1 = np.cross(n, vec)
        t1 = t1 / np.linalg.norm(t1)
        t2 = np.cross(n, t1)
        t2 = t2 / np.linalg.norm(t2)

        # Center of mass to contact point
        r = con_pts[i] - cm
        
        for j in range(n_edges):
            # Angle around friction cone
            angle = 2.0 * np.pi * j / n_edges
            # Primitive force = normal F + tangential F. Magnitude ||f|| = sqrt(1 + mu^2)
            f = n + mu * (np.cos(angle) * t1 + np.sin(angle) * t2)
            # Primitive torque = cross product of r and f_k
            tau = np.cross(r, f)
            # Wrench = [f^T, tau^T]
            row = i * n_edges + j
            W[row, 0:3] = f
            W[row, 3:6] = tau

    ##########################
    return W


########## Task 2: Grasp Quality Evaluation ##########

def eval_Q(mesh, grasp, mu=0.2, n_edges=8, lmbd=1.0):
    """
    Evaluate the L1 quality of a grasp.
    args:   mesh: The object mesh model.
                  Type: trimesh.base.Trimesh
           grasp: The indices of the mesh triangles being contacted.
                  Type: list of int
              mu: The friction coefficient of the mesh surface.
                  (default: 0.2)
         n_edges: The number of edges of the friction polyhedral cone.
                  Type: int (default: 8)
            lmbd: The scale of torque magnitude.
                  (default: 1.0)
    returns:   Q: The L1 quality score of the given grasp.
    """
    ########## TODO ##########
    Q = -np.inf

    # Find primitive wrenches using Task 1
    W = primitive_wrenches(mesh, grasp, mu=mu, n_edges=n_edges)

    # Scale torques by lambda
    W[:, 3:6] *= lmbd

    # Build the convex hull
    try:
        hull = scipy.spatial.ConvexHull(W)
    except Exception:
        # Catch degenerate case
        return -np.inf

    # L1 quality = min of signed distances from origin to hyperplane
    #            = min of opposite number of hyperplane offsets (last column of equations attribute)
    Q = float(np.min(-hull.equations[:, -1]))

    ##########################
    return Q


########## Task 3: Stable Grasp Sampling ##########

def sample_stable_grasp(mesh, thresh=0.0):
    """
    Sample a stable grasp such that its L1 quality is larger than a threshold.
    args:     mesh: The object mesh model.
                    Type: trimesh.base.Trimesh
            thresh: The threshold for stable grasp.
                    (default: 0.0)
    returns: grasp: The stable grasp represented by the indices of triangles.
                    Type: list of int
                 Q: The L1 quality score of the sampled grasp, 
                    expected to be larger than thresh.
    """
    ########## TODO ##########
    grasp = None
    Q = -np.inf

    while Q <= thresh:
        # Randomly sample 3 faces as contact points
        sample = list(np.random.choice(len(mesh.faces), size=3, replace=False))
        q = eval_Q(mesh, sample)
        if q > thresh:
            grasp = sample
            Q = q

    ##########################
    return grasp, Q


########## Task 4: Grasp Optimization ##########

def find_neighbors(mesh, tr_id, eta=1):
    """
    Find the eta-order neighbor faces (triangles) of tr_id on the mesh model.
    args:       mesh: The object mesh model.
                      Type: trimesh.base.Trimesh
               tr_id: The index of the query face (triangle).
                      Type: int
                 eta: The maximum order of the neighbor faces:
                      Type: int
    returns: nbr_ids: The list of the indices of the neighbor faces.
                      Type: list of int
    """
    ########## TODO ##########
    nbr_ids = []

    visited = {tr_id}
    frontier = {tr_id}

    for _ in range(eta):
        next_frontier = set()
        for face in frontier:
            # Get the 3 vertices of this triangle face
            vertices = mesh.faces[face]
            for v in vertices:
                # Iterate through all faces containing vertex v
                for nbr in mesh.vertex_faces[v]:
                    if nbr != -1 and nbr not in visited:
                        next_frontier.add(nbr)
        visited |= next_frontier
        frontier = next_frontier

    # Remove the query face
    visited.discard(tr_id)
    nbr_ids = list(visited)

    ##########################
    return nbr_ids

def local_optimal(mesh, grasp):
    """
    Find the optimal neighbor grasp of the given grasp.
    args:     mesh: The object mesh model.
                    Type: trimesh.base.Trimesh
             grasp: The indices of the mesh triangles being contacted.
                    Type: list of int
    returns: G_opt: The optimal neighbor grasp with the highest quality.
                    Type: list of int
             Q_max: The L1 quality score of G_opt.
    """
    ########## TODO ##########

    # Build neighbor set for each contact
    nbr_sets = [find_neighbors(mesh, face_id, eta=1) for face_id in grasp]

    G_opt = list(grasp)
    Q_max = -np.inf

    # Test every combination of 1 neighbor per contact (Cartesian product)
    for combo in it.product(*nbr_sets):
        candidate = list(combo)

        # Skip if any 2 contacts are on same face
        if len(set(candidate)) < len(candidate):
            continue

        # Evaluate quality of candidate grasp and update optimal
        q = eval_Q(mesh, candidate)
        if q > Q_max:
            Q_max = q
            G_opt = candidate

    ##########################
    return G_opt, Q_max

def optimize_grasp(mesh, grasp):
    """
    Optimize the given grasp and return the trajectory.
    args:    mesh: The object mesh model.
                   Type: trimesh.base.Trimesh
            grasp: The indices of the mesh triangles being contacted.
                   Type: list of int
    returns: traj: The trajectory of the grasp optimization.
                   Type: list of grasp (each grasp is a list of int)
    """
    traj = []
    ########## TODO ##########
   
    traj = [list(grasp)]
    curr_grasp = list(grasp)
    curr_Q = eval_Q(mesh, curr_grasp)

    while True:
        G_opt, Q_max = local_optimal(mesh, curr_grasp)

        # If neighbor grasp improves current quality, add to trajectory
        if Q_max > curr_Q:
            curr_grasp = G_opt
            curr_Q = Q_max
            traj.append(list(curr_grasp))
        else:
            # Reached local optimum when no neighbor grasp improves quality
            break

    ##########################
    return traj


########## Task 5: Grasp Optimization with Reachability ##########

def optimize_reachable_grasp(mesh, r=0.5):
    """
    Sample a reachable grasp and optimize it.
    args:    mesh: The object mesh model.
                   Type: trimesh.base.Trimesh
                r: The reachability measure. (default: 0.5)
    returns: traj: The trajectory of the grasp optimization.
                   Type: list of grasp (each grasp is a list of int) 
    """
    traj = []
    ########## TODO ##########
   
    # Helper function to check if a grasp satisfies the reachability constraint
    def reachable(grasp):
        con_pts = utils.get_centroid_of_triangles(mesh, grasp)
        centroid = con_pts.mean(axis=0)
        avg_dist = np.mean(np.linalg.norm(con_pts - centroid, axis=1))
        return avg_dist < r

    # Sample a reachable starting grasp
    grasp = None
    while grasp is None:
        candidate = list(np.random.choice(len(mesh.faces), size=3, replace=False))
        if reachable(candidate):
            grasp = candidate

    traj = [list(grasp)]
    curr_grasp = list(grasp)
    curr_Q = eval_Q(mesh, curr_grasp)

    # Optimize grasp under reachability constraint
    while True:
        # Build neighbor set for each contact (same as Task 4)
        nbr_sets = [find_neighbors(mesh, face_id, eta=1) for face_id in curr_grasp]

        G_opt = None
        Q_max = curr_Q

        # Search all neighbor combinations
        for combo in it.product(*nbr_sets):
            candidate = list(combo)

            # Filter duplicates and unreachable candidates
            if len(set(candidate)) < len(candidate):
                continue
            if not reachable(candidate):
                continue

            # Evaluate quality of candidate grasp and update optimal
            q = eval_Q(mesh, candidate)
            if q > Q_max:
                Q_max = q
                G_opt = candidate

        # Reached local optimum when no neighbor grasp improves quality
        if G_opt is None:
            break

        curr_grasp = G_opt
        curr_Q = Q_max
        traj.append(list(curr_grasp))

    ##########################
    return traj
